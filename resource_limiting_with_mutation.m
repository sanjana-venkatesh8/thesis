light_exp_lengths = 5 * ones(1, length(light_exp_times)); %[10, 10, 10, 10, 10];

function dxdt = population_odes(t, x)
    %########## PARAMETERS ##########    
    g_eng = 0.005; g_esc = 0.15; g_wt = 0.23;
    d_wt = 0.004; d_mut = 0.1; % h^-1
    eng2mut = @(t) e2m(t);    
    mut2hit = @(t) 5e-4 * one(t);
    hit2esc = @(t) 5e-2 * one(t);

    P_total = 100000;
    P_eng_noLight = 1300;
    P_eng_light = P_total;
    P_mut = 3000;
    P_hit = 8000;
    P_esc = 8000;
    space_const = 0.2;
    %################################

    eng = x(1); % engineered cells
    mut = x(2); % mutators
    hit = x(3); % hitchhikers
    esc = x(4); % escaped cells

    logistic = 1 - (eng+mut+hit+esc) / P_total;

    % dengdt = ((g_eng - d_wt) * eng - eng2mut(t) * eng) * (1 - (eng + space_const*(mut+hit+esc))/P_eng_noLight) * (1 - light(t)) ... % dynamics in growth restriction
    %        + ((g_wt - d_wt) * eng - eng2mut(t) * eng) * (1 - (eng + space_const*(mut+hit+esc))/P_eng_light) * light(t);  % dynamics in growth permission
    % dmutdt = ((g_eng - d_mut) * mut + eng2mut(t) * eng - mut2hit(t) * mut) * (1 - (mut + space_const*(eng+hit+esc))/P_mut);
    % dhitdt = ((g_esc - d_mut) * hit + mut2hit(t) * mut - hit2esc(t) * hit) * (1 - (hit + space_const*(eng+mut+esc))/P_hit);
    % descdt = ((g_esc - d_wt) * esc + hit2esc(t) * hit) * (1 - (esc + space_const*(eng+mut+hit))/P_esc);

    dengdt = ((g_eng - d_wt) * eng - eng2mut(t) * eng) * logistic * (1 - light(t)) ... % dynamics in growth restriction
           + ((g_wt - d_wt) * eng - eng2mut(t) * eng) * logistic * light(t);  % dynamics in growth permission
    dmutdt = ((g_eng - d_mut) * mut + eng2mut(t) * eng - mut2hit(t) * mut) * logistic;
    dhitdt = ((g_esc - d_mut) * hit + mut2hit(t) * mut - hit2esc(t) * hit) * logistic;
    descdt = ((g_esc - d_wt) * esc + hit2esc(t) * hit) * logistic;

    dxdt = [dengdt; dmutdt; dhitdt; descdt];
end

function y = light(t)
    %########## PARAMETERS ##########
    % light_exp_times = [10, 30, 70];
    % light_exp_lengths = [5, 10, 15];
    global light_exp_times light_exp_lengths;
    %################################

    y = 0;
    for i = 1:length(light_exp_times)
        y = y + heaviside(t - light_exp_times(i)) ...
            - heaviside(t- (light_exp_times(i) + light_exp_lengths(i)));
    end
end

function y = e2m(t)
    %########## PARAMETERS ##########
    delay = 3;
    spike_length = 10;
    global light_exp_times light_exp_lengths;
