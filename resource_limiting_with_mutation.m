function y = spike(t, length)
    %########## PARAMETERS ##########
    r_min = 5e-5; 
    r_max = 5e-4;
    t0 = 0; 
    tf = t0 + length;
    %################################

    slope = (r_max - r_min) / (0.5 * (tf - t0));
    tm = (tf + t0) / 2;

    y = r_min * ones(size(t));

    rise = (t >= t0) & (t < tm);
    fall = (t >= tm) & (t < tf);

    y(rise) = slope * (t(rise) - t0) + r_min;
    y(fall) = -slope * (t(fall) - tm) + r_max;
end

function y = one(t)
    y = 1;
end

